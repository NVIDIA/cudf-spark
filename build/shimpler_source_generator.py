"""Materialize resolved shim sources for the Jython 2.7 build task."""

import os
import re
import shutil

from shimpler_source_resolver import resolve_sources, scan_module_sources


SPARK_CLASSIFIER = '$_spark.version.classifier_'
PACKAGE_CLASSIFIER = re.compile(
    r'^[ \t]*package[ \t]+[^\r\n]*(' + re.escape(SPARK_CLASSIFIER) + r')', re.MULTILINE)


def _is_within(root, candidate):
    prefix = root if root.endswith(os.sep) else root + os.sep
    return candidate == root or candidate.startswith(prefix)


def _has_parent_reference(path):
    path = path.replace(os.altsep, os.sep) if os.altsep else path
    return os.pardir in path.split(os.sep)


def _validate_generated_path(output_root, path):
    """Reject output paths that escape the output root or traverse a symlink."""
    if _has_parent_reference(output_root) or _has_parent_reference(path):
        raise ValueError('Generated source path contains a parent reference: %s' % path)
    root = os.path.abspath(output_root)
    candidate = os.path.abspath(path)
    if not _is_within(root, candidate):
        raise ValueError('Generated source path is outside the output root: %s' % path)
    current = candidate
    while True:
        if os.path.islink(current):
            raise ValueError('Generated source path traverses a symlink: %s' % current)
        if current == root:
            break
        current = os.path.dirname(current)


def _common_output_root(module_root, generated_root):
    """Return the nearest lexical ancestor shared by source and output roots."""
    root = os.path.abspath(module_root)
    generated = os.path.abspath(generated_root)
    while not _is_within(root, generated):
        parent = os.path.dirname(root)
        if parent == root:
            return root
        root = parent
    return root


def generate_sources(module_root, generated_root, graph, target, valid_targets=None,
                     allowed_external_targets=(), output_root=None):
    """Replace generated main/test outputs with the target's selected sources.

    Selection and validation finish before old outputs are removed. The caller's
    cache marker is written only after this function succeeds, so an interrupted
    generation is retried by Maven.
    """
    # Other Scala POMs may define selectors that are inert in this build. Parse
    # against the repository-wide target set, but resolve using only this graph.
    variants, unannotated = scan_module_sources(
        module_root, graph if valid_targets is None else valid_targets,
        allowed_external_targets)
    if unannotated:
        raise ValueError('No shim selector block in %s' % unannotated[0])
    selected = resolve_sources(graph, variants, target)

    if output_root is None:
        output_root = _common_output_root(module_root, generated_root)
    scope_roots = [os.path.join(generated_root, scope) for scope in ('main', 'test')]
    for path in [generated_root] + scope_roots:
        _validate_generated_path(output_root, path)
    for scope_root in scope_roots:
        if os.path.isdir(scope_root):
            shutil.rmtree(scope_root)

    for logical in sorted(selected):
        source = selected[logical].physical_path
        destination = os.path.join(generated_root, *logical.split('/')[1:])
        parent = os.path.dirname(destination)
        if not os.path.isdir(parent):
            os.makedirs(parent)
        with open(source, 'r') as source_file:
            contents = source_file.read()
        match = PACKAGE_CLASSIFIER.search(contents)
        if match is None:
            os.symlink(os.path.abspath(source), destination)
        else:
            with open(destination, 'w') as output:
                output.write(contents[:match.start(1)])
                output.write('spark' + target)
                output.write('\n')
                output.write('''
/*
!!! DO NOT EDIT THIS FILE !!!

This file has been generated from the original

%s

by interpolating $_spark.version.classifier_=%s

Be sure to edit the original file if required

*/
                ''' % (source, 'spark' + target))
                output.write(contents[match.end(1):])
    return selected
